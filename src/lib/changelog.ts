export const isChangelogModalOpen = writable<boolean>(false);

export function getLatestChangelog(): ChangelogEntry {
  return CHANGELOG_HISTORY[0];
}

export function getCurrentVersionChangelog(): ChangelogEntry {
  const found = CHANGELOG_HISTORY.find((e) => e.version === APP_VERSION);
  return found || CHANGELOG_HISTORY[0];
}
