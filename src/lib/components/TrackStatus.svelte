<!--
  Статус трека в списке: номер по порядку, наушники у играющего, крестик у забаненного,
  треугольник «плей» под курсором.

  Почему это отдельный компонент. Один и тот же блок из двух ячеек был скопирован в шесть
  списков (локальные файлы, лайки, плейлист, альбом артиста, популярные треки артиста,
  поиск), причём в трёх из них наушники были вклеены сырым `<svg>` вместо иконки. Логика
  подмены при этом везде была одна — и везде одинаково неправильная (см. ниже), так что
  править приходилось шесть раз, а добавить седьмой список означало скопировать ошибку
  ещё раз.

  Что было неправильно. Ячейка статуса гасилась на `group-hover` без исключений, а ячейка
  «плей» на нём же показывалась. Для не играющего трека это верно, но для играющего —
  нет: пользователь включал трек, курсор оставался на строке, и вместо наушников он
  продолжал видеть «плей». Статус появлялся только когда курсор уходил со строки, то есть
  ровно тогда, когда он уже не нужен. Здесь такой трек «закреплён» (`locked`): ячейка
  «плей» для него не выводится вообще, поэтому подменять нечего.

  Подмена сделана на `.interactive-item:hover` (правила в app.css), а не на Tailwind-группе.
  Причина практическая: строки носят разные группы — `group` в одних списках и `group/track`
  в других, — и одним селектором их не покрыть, а `interactive-item` есть на каждой строке,
  по которой можно щёлкнуть. Заодно это само выключает подмену у забаненных строк: они этот
  класс не носят.
-->
<script lang="ts">
  import { Play, Headphones, X } from 'lucide-svelte';

  /** Порядковый номер в списке, с нуля. */
  export let index: number;
  export let isActive = false;
  /** Значение стора `isPlaying` — статус ставится только у реально играющего трека. */
  export let playing = false;
  export let banned = false;
  /** `sm` — плотные списки (номер справа), `md` — поиск (номер по центру). */
  export let size: 'sm' | 'md' = 'sm';

  $: iconSize = size === 'md' ? 16 : 14;
  $: locked = banned || (isActive && playing);
</script>

{#if locked}
  <div class="track-status" data-size={size}>
    {#if banned}
      <X size={iconSize} class="text-red-500" />
    {:else}
      <Headphones size={iconSize} class="text-primary" />
    {/if}
  </div>
{:else}
  <div class="track-status track-status-idle" data-size={size}>{index + 1}</div>
  <div class="track-status track-status-play" data-size={size}>
    <Play size={iconSize} fill="currentColor" />
  </div>
{/if}
