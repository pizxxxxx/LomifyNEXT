/**
 * Нажатие вдавливает элемент в глубину: `:active` ставит `perspective(P) translateZ(-z)`, а
 * это ровно однородный масштаб P/(P+z) — бокс УМЕНЬШАЕТСЯ. Отсюда дефект, который выглядит
 * как «кнопка нажимается визуально, а действие не срабатывает».
 *
 * ── Почему клик пропадал ─────────────────────────────────────────────────────────────
 * Кнопки «Светлее»/«Темнее» в настройках — 346×51 при `--depth-perspective: 900px` и
 * `--depth-press: -26px` (значение Aurora). Масштаб 900/926 = 0.9719, то есть по 4.9px с
 * каждой вертикальной грани и по 0.7px сверху и снизу уходят из-под курсора.
 *
 * Дальше расходятся две вещи, которые обычно совпадают:
 *   • `:active` держится, пока кнопка мыши нажата, даже если курсор ушёл с элемента, —
 *     поэтому нажатие ВИДНО;
 *   • `click` браузер отправляет в ближайшего общего предка целей `mousedown` и `mouseup`.
 *     Кнопка сжалась, `mouseup` попал в контейнер под ней — и клик уходит контейнеру,
 *     на котором обработчика нет.
 * Результат: продавилось, подсветилось, ничего не произошло. И «не всегда» — потому что
 * зависит от того, попал ли курсор в эту кромку шириной пять пикселей.
 *
 * ── Две меры, а не одна ──────────────────────────────────────────────────────────────
 * 1. ЗАХВАТ УКАЗАТЕЛЯ. `setPointerCapture` на `pointerdown` перенаправляет элементу все
 *    последующие события указателя, включая совместимостные события мыши: `mouseup`
 *    приходит на кнопку, а не на то, что оказалось под курсором, и `click` считается от
 *    неё. Это работает независимо от того, на сколько и в какую сторону уехал бокс, —
 *    поэтому мера основная. Она же закрывает случаи, которых геометрия не покрывает
 *    вовсе: элемент, уехавший из-под курсора СДВИГОМ (у сдвига неподвижной точки нет), и
 *    элемент, перерисованный под курсором за время нажатия. Захватывает при этом та
 *    кнопка внутри поверхности, по которой нажали (см. `CLICKABLE`), иначе мера отбирала
 *    бы клик у неё в пользу карточки.
 *
 * 2. ТОЧКА ОТСЧЁТА. `transform-origin` уезжает в место нажатия. Центр масштабирования —
 *    его неподвижная точка, поэтому пиксель под курсором остаётся под курсором при любой
 *    величине усадки. Само по себе это тоже лечит потерю клика, но только для чистого
 *    масштаба; здесь мера оставлена ради вида — поверхность проминается там, где на неё
 *    давят, а не отъезжает к центру равномерно.
 *
 * Масштаб нажатия не тронут ни там, ни там: вдавливание ощущается ровно как раньше.
 *
 * Переменные не снимаются на `pointerup` сознательно: отпускание доезжает переходом, и
 * сброс `transform-origin` посреди него дёрнул бы элемент. Их перезаписывает следующее
 * нажатие, а на покоящемся элементе `transform: none` — и точка отсчёта ни на что не
 * влияет.
 *
 * ── Срабатывание на нажатии, а не на отпускании ──────────────────────────────────────
 * Кнопки и тумблеры выполняют действие на `pointerdown`. Дело не в миллисекундах самих по
 * себе: у переключателя стиля волны и у тумблеров в настройках отклика на нажатие не было
 * вообще — ни правила `:active`, ни смены цвета, — а плашка переключателя переезжала за
 * 420 мс. Между нажатием и первым признаком, что оно принято, лежала почти половина
 * секунды пустоты, и читается это ровно как «кнопка не прожимается». Отклик добавлен
 * отдельно (`.seg-item:active`, `.switch:active` в app.css), но одного отклика мало: само
 * действие всё равно ждало отпускания.
 *
 * Как сделано. На `pointerdown` по кнопке отправляется `click` со всеми полями настоящего
 * (координаты, модификаторы, `pointerId`), а следующий НАСТОЯЩИЙ клик от того же нажатия
 * глушится в фазе захвата на окне — без этого каждый обработчик срабатывал бы дважды, то
 * есть тумблер возвращался бы в исходное состояние. Отличаются они по `isTrusted`: у
 * отправленного скриптом он `false`, у браузерного — `true`.
 *
 * Побочно этим снимается и потеря клика, разобранная выше, — целиком и сразу по всем
 * причинам: куда попадёт `mouseup`, больше не важно, действие уже выполнено.
 *
 * Чем платим и где отключено. Нажатие становится необратимым: отвести курсор и отпустить
 * мимо, чтобы отменить, уже нельзя. Для необратимого действия без подтверждения это плохой
 * обмен, поэтому у таких стоит `data-press-late` — кнопки окна в титлбаре (случайное
 * нажатие закрыло бы приложение) и удаление плейлиста в медиатеке (удаляет молча, без
 * `confirm`). Тому, что спрашивает подтверждение, опт-аут не нужен: подтверждение и есть
 * отмена.
 *
 * Тач-ввод не затронут: там нажатие по кнопке — ещё и начало прокрутки пальцем, и
 * срабатывание на касании отдавало бы действие каждому, кто просто пролистнул список.
 * Ссылки и поля ввода тоже: у перехода по ссылке и у постановки курсора в текст своя
 * механика, раннее срабатывание ей ничего не добавляет.
 */

/** Всё, что вдавливается по `:active`. Совпадает со списком в app.css. */
const PRESSABLE = '.interactive-item, .glass-button, .play-btn';

/**
 * Что внутри вдавливаемой поверхности само обрабатывает нажатие.
 *
 * Нужен затем, что захват (мера 1) отбирает клик у вложенных кнопок: на карточке-плитке
 * `mousedown` и `mouseup` оба уходят захватившей поверхности, а `click` браузер отправляет
 * в ближайшего общего предка их целей — то есть тоже поверхности, а не кнопке. Кнопка при
 * этом визуально нажимается, но её обработчик (и её `stopPropagation`) не вызывается, зато
 * срабатывает клик по самой карточке. Ровно так пропала кнопка «Превью плейлиста» на полке:
 * нажатие раскрывало плейлист вместо трейлера.
 */
const CLICKABLE = 'button, a, [role="button"], [role="link"], input, select, textarea, summary';

/**
 * Что срабатывает на нажатии, а не на отпускании. Только кнопки и роли, которые ведут себя
 * как кнопка; ссылки, поля ввода и `summary` из списка исключены намеренно (см. заголовок).
 */
const PRESS_ACTIVATE =
  'button, [role="button"], [role="switch"], [role="radio"], [role="checkbox"], [role="tab"], [role="menuitem"], [role="option"]';

/** Отказ от раннего срабатывания: необратимое действие, которое ничего не спрашивает. */
const PRESS_LATE = '[data-press-late]';

function clampPct(v: number): number {
  return v < 0 ? 0 : v > 100 ? 100 : v;
}

/**
 * Ждём настоящий клик от текущего нажатия, чтобы его погасить. Флаг, а не сверка цели: и
 * усадка, и перерисовка меняют то, куда браузер отправит клик — ровно из-за этого он и
 * терялся, — а вот парность «одно нажатие, один клик» не ломается ничем.
 */
let awaitingRealClick = false;
let clickWatchdog = 0;

function armClickSuppression() {
  awaitingRealClick = true;
  clearTimeout(clickWatchdog);
  // Страховка: клика может не быть вовсе — указатель потерян, элемент исчез вместе с
  // разметкой. Оставленный флаг съел бы следующее, уже чужое нажатие.
  clickWatchdog = window.setTimeout(() => {
    awaitingRealClick = false;
  }, 700);
}

function onClickCapture(e: MouseEvent) {
  if (!awaitingRealClick || !e.isTrusted) return;
  awaitingRealClick = false;
  clearTimeout(clickWatchdog);
  // Действие уже выполнено на нажатии. Гасим и всплытие, и действие по умолчанию: без
  // первого обработчики сработали бы по второму разу, без второго — встроенное поведение
  // элемента (у флажка это вернуло бы галочку назад).
  e.preventDefault();
  e.stopImmediatePropagation();
}

/**
 * Отправляет клик от имени нажатия. Не `el.click()`: тот присылает событие с нулевыми
 * координатами и `detail: 0`, а обработчики, которые ставят меню в точку нажатия, читают
 * `clientX`/`clientY` — и уехали бы в левый верхний угол окна.
 */
function activate(el: Element, e: PointerEvent) {
  armClickSuppression();
  el.dispatchEvent(
    new PointerEvent('click', {
      bubbles: true,
      cancelable: true,
      composed: true,
      view: window,
      detail: 1,
      button: 0,
      buttons: 0,
      clientX: e.clientX,
      clientY: e.clientY,
      screenX: e.screenX,
      screenY: e.screenY,
      ctrlKey: e.ctrlKey,
      shiftKey: e.shiftKey,
      altKey: e.altKey,
      metaKey: e.metaKey,
      pointerId: e.pointerId,
      pointerType: e.pointerType,
      isPrimary: true,
    }),
  );
}

/** Выключенная кнопка не нажимается и не срабатывает — ни рано, ни поздно. */
function isDisabled(el: Element): boolean {
  return (el as HTMLButtonElement).disabled === true || el.getAttribute('aria-disabled') === 'true';
}

function onPointerDown(e: PointerEvent) {
  const target = e.target instanceof Element ? e.target : null;
  if (!target) return;

  const el = target.closest(PRESSABLE) as HTMLElement | null;
  if (el) {
    const rect = el.getBoundingClientRect();
    if (rect.width && rect.height) {
      const ox = ((e.clientX - rect.left) / rect.width) * 100;
      const oy = ((e.clientY - rect.top) / rect.height) * 100;
      // Обрезаем по боксу: нажать можно и по всплывающему меню, которое вылезает за кромку
      // карточки, а точка отсчёта за пределами элемента увела бы усадку в сторону.
      el.style.setProperty('--press-ox', `${clampPct(ox).toFixed(1)}%`);
      el.style.setProperty('--press-oy', `${clampPct(oy).toFixed(1)}%`);
    }
  }

  // Захват только для мыши и пера. На тач-вводе он отобрал бы у страницы прокрутку
  // пальцем, начатую с карточки: панорамирование браузер ведёт по тем же событиям
  // указателя, и перенаправление их одному элементу читалось бы как «палец не двигается».
  //
  // Ползунки (`$lib/actions/dragValue`) захватывают указатель сами, и это не конфликт:
  // здесь фаза захвата, их обработчик — на всплытии, то есть позже, а последний вызов
  // `setPointerCapture` побеждает. Освобождать захват вручную не нужно — браузер снимает
  // его на `pointerup` и `pointercancel`.
  if (e.pointerType === 'touch') return;
  // Только основная кнопка: у правой своё меню, у средней своё поведение, и ни то ни
  // другое не нажатие.
  if (e.button !== 0 || !e.isPrimary) return;

  const early = target.closest(PRESS_ACTIVATE) as HTMLElement | null;
  const activatable = early && !early.closest(PRESS_LATE) && !isDisabled(early) ? early : null;

  // Захват вешаем на ту кнопку внутри поверхности, по которой нажали, а не на поверхность:
  // тогда и `mouseup`, и `click` считаются от кнопки — она получает своё нажатие, а
  // карточка под ней не получает чужое. Если нажали по самой поверхности (или кнопка
  // снаружи неё), цель прежняя. У кнопки, срабатывающей на нажатии, захват нужен ещё и
  // затем, чтобы настоящий клик пришёл гарантированно: тогда его глушение всегда находит
  // ровно то событие, для которого предназначено.
  const clickable = target.closest(CLICKABLE) as HTMLElement | null;
  const captureTarget = activatable ?? (clickable && el?.contains(clickable) ? clickable : el);
  if (captureTarget) {
    try {
      captureTarget.setPointerCapture(e.pointerId);
    } catch {
      // Указателя уже нет (успел отпуститься) — терять тут нечего, нажатие просто пройдёт
      // как раньше.
    }
  }

  if (activatable) activate(activatable, e);
}

/** Returns a teardown function, so callers can register it from `onMount`. */
export function trackPress(): () => void {
  if (typeof window === 'undefined') {
    return () => {};
  }

  // Фаза захвата: нажатие может быть погашено `stopPropagation` где-нибудь по дороге
  // (так делают перетаскиваемые ползунки), а точка отсчёта нужна раньше любого разбора.
  window.addEventListener('pointerdown', onPointerDown, { capture: true, passive: true });
  // Настоящий клик глушим на окне и тоже в фазе захвата — это самая ранняя точка, где его
  // видно; ниже по дереву его успели бы обработать. `passive` здесь нельзя: правило как
  // раз в том, чтобы вызвать `preventDefault`.
  window.addEventListener('click', onClickCapture, { capture: true });

  return () => {
    window.removeEventListener('pointerdown', onPointerDown, { capture: true });
    window.removeEventListener('click', onClickCapture, { capture: true });
    clearTimeout(clickWatchdog);
    awaitingRealClick = false;
  };
}
