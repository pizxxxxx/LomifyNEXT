/**
 * Контракт события `audio:fft` — одно место, где записано, что именно шлёт бэкенд.
 *
 * `src-tauri/src/audio/analyser.rs` отдаёт 64 полосы спектра как **f32 в диапазоне 0..1**:
 * величины уже прошли лог-сжатие, нормализацию и сглаживание с предыдущим кадром, так что
 * умножать или делить их не нужно — только растянуть по высоте картинки. Кадр из одних нулей
 * — это отдельное сообщение «звука больше нет»; его шлют один раз после паузы или тишины,
 * чтобы визуализация успела погаснуть, а не замерла на последнем всплеске.
 *
 * Зачем отдельный модуль на пятнадцать строк. Знание о диапазоне жило в комментариях двух
 * компонентов, и в обоих было неверным — «values are 0-255». И лента на главной, и полосы в
 * полном экране делили значение на 255, то есть получали примерно ноль: пока играла тишина,
 * картинка выглядела живой от синтетического движения, а с началом трека схлопывалась в
 * прямую линию. Симптом читался как «визуализация не работает именно когда играет музыка».
 * Теперь диапазон описан один раз, и разойтись с analyser.rs он может только вместе с ним.
 */
export const FFT_BINS = 64;

/**
 * Переливает полезную нагрузку события в буфер картинки. Значения подрезаются по 0..1 (в том
 * числе `NaN` превращается в ноль — иначе одна испорченная полоса отравляет сглаживание
 * навсегда), а хвост буфера гасится: если полос пришло меньше, чем ждёт картинка, в остатке
 * иначе навсегда застынет предыдущий кадр.
 *
 * Возвращает `false`, если в событии не было ничего — тогда вызывающему не надо трогать ни
 * буфер, ни отметку времени последнего спектра.
 */
export function readFftInto(payload: ArrayLike<number> | null | undefined, out: Float32Array): boolean {
  if (!payload || payload.length === 0) return false;

  const n = Math.min(out.length, payload.length);
  for (let i = 0; i < n; i++) {
    const v = payload[i];
    out[i] = v > 0 ? (v < 1 ? v : 1) : 0;
  }
  for (let i = n; i < out.length; i++) out[i] = 0;

  return true;
}
